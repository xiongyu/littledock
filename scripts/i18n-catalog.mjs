import { readFile, writeFile, readdir, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join, relative } from 'node:path'
import { parseLocaleBundle } from '../shared/src/i18n.ts'

const root = fileURLToPath(new URL('../', import.meta.url)), writing = process.argv.includes('--write')
const packages = [{ id: 'core', directory: 'frontend/src' }]
for (const parent of ['backend/plugins', 'plugins', 'examples/plugins']) for (const entry of await readdir(join(root, parent), { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  const directory = parent + '/' + entry.name
  try { const manifest = JSON.parse(await readFile(join(root, directory, 'webnav.plugin.json'), 'utf8')); packages.push({ id: manifest.id, directory, manifest }) } catch (error) { if (error.code !== 'ENOENT') throw error }
}
const generated = ["// Generated by scripts/i18n-catalog.mjs. Dictionaries belong to their source plugin.", "import type { LocaleBundle } from '@webnav/shared'"]
const types = ["// Generated from each plugin's default dictionary; do not edit.", 'export interface LocaleNamespaceMap {']
const records = [], errors = []
for (const [index, pkg] of packages.entries()) {
  const base = join(root, pkg.directory, 'locales'); await mkdir(base, { recursive: true })
  const read = async locale => { try { return JSON.parse(await readFile(join(base, locale + '.json'), 'utf8')) } catch (error) { if (error.code === 'ENOENT' && writing) return {}; throw error } }
  const zh = await read('zh-CN'), en = await read('en')
  if (pkg.manifest) {
    const metadata = { 'metadata.name': pkg.manifest.name, 'metadata.description': pkg.manifest.description }
    for (const field of pkg.manifest.configFields ?? []) metadata[`configFields.${field.key}.label`] = field.label
    for (const tool of pkg.manifest.contributes?.tools ?? []) metadata[`tools.${tool.id}.title`] = tool.title
    for (const font of pkg.manifest.contributes?.fonts ?? []) { metadata[`fonts.${font.flag}.name`] = font.name; if (font.group) metadata[`fonts.${font.flag}.group`] = font.group }
    if (pkg.manifest.contributes?.settings) metadata['settings.title'] = pkg.manifest.contributes.settings.title
    for (const family of ['menuItems', 'uiItems', 'menuPoints', 'uiPoints']) for (const item of pkg.manifest.contributes?.[family] ?? []) for (const key of ['label', 'title', 'purpose']) if (item[key]) metadata[`${family}.${item.id}.${key}`] = item[key]
    for (const [key, text] of Object.entries(metadata)) if (writing) zh[key] ??= text; else if (!Object.hasOwn(zh, key)) errors.push(`${pkg.id}: missing ${key}`)
    const declaration = { defaultLocale: 'zh-CN', locales: { 'zh-CN': 'locales/zh-CN.json', en: 'locales/en.json' } }
    if (writing) { pkg.manifest.i18n = declaration; await writeFile(join(root, pkg.directory, 'webnav.plugin.json'), JSON.stringify(pkg.manifest, null, 2) + '\n') }
    else if (JSON.stringify(pkg.manifest.i18n) !== JSON.stringify(declaration)) errors.push(`${pkg.id}: declare the shipped Chinese and English resources`)
  }
  if (writing) { await writeFile(join(base, 'zh-CN.json'), JSON.stringify(zh, null, 2) + '\n'); await writeFile(join(base, 'en.json'), JSON.stringify(en, null, 2) + '\n') }
  parseLocaleBundle({ defaultLocale: 'zh-CN', locales: { 'zh-CN': zh, en } })
  if (!writing) for (const key of Object.keys(zh)) if (!Object.hasOwn(en, key) || !en[key].trim()) errors.push(`${pkg.id}: English translation missing: ${key}`)
  if (pkg.id === 'core' || pkg.id.startsWith('builtin.')) {
    let path = relative(join(root, 'frontend/src'), base).replaceAll('\\', '/'); if (!path.startsWith('.')) path = './' + path
    generated.push(`import zh${index} from '${path}/zh-CN.json' with { type: 'json' }`, `import en${index} from '${path}/en.json' with { type: 'json' }`)
    records.push(`  '${pkg.id}': { defaultLocale: 'zh-CN', locales: { 'zh-CN': zh${index}, en: en${index} } },`)
    types.push(`  '${pkg.id}': keyof typeof import('${path}/zh-CN.json')`)
  }
}
generated.push('export const builtinLocales: Record<string, LocaleBundle> = {', ...records, '}')
types.push('}')
for (const [file, content] of [['i18n-builtins.ts', generated], ['i18n-keys.ts', types]]) {
  const output = content.join('\n') + '\n', target = join(root, 'frontend/src', file)
  if (writing) await writeFile(target, output)
  else if (await readFile(target, 'utf8') !== output) errors.push(`${file} is out of date; run pnpm i18n:generate`)
}
if (errors.length) { console.error(errors.join('\n')); process.exitCode = 1 } else console.log(`Validated ${packages.length} plugin/host locale catalogs.`)
