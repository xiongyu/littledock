  await row('node-fixture').click({ button: 'right' })
  await page.getByRole('menuitem', { name: '查看网络连接', exact: true }).click()
  await page.getByRole('cell', { name: '127.0.0.1:5151', exact: true }).waitFor()
  await row('node-fixture').click({ button: 'right' })
  await page.getByRole('menuitem', { name: '强制结束…', exact: true }).click()
  await page.getByRole('heading', { name: '强制结束进程', exact: true }).waitFor()
  assert.match(await page.locator('.tm-action-dialog').innerText(), /node-fixture[\s\S]*PID 120/)
  assert.equal(fixture.stats.applies, 0, 'menu never skips the existing confirmation')
  await button('取消').click()
  // Online lookup is checked without making any external request.
  await page.evaluate(() => { window.open = (...args) => { window.lookupArgs = args; return null } })
  await row('node-fixture').click({ button: 'right' })
  await page.getByRole('menuitem', { name: '在线搜索进程名', exact: true }).click()
  assert.deepEqual(await page.evaluate(() => window.lookupArgs), ['https://www.bing.com/search?q=node-fixture', '_blank', 'noopener,noreferrer'])
