  const predecessor = monitor.processes.find(item => item.pid === 121)
  monitor.processes = monitor.processes.filter(item => item.pid !== 121)
  await refresh()
  assert.deepEqual(await order(), pinnedOrder, 'an exited predecessor cannot move the selected row')
  assert.match(await row('renderer-fixture').innerText(), /本次未采集/)
